func TestIsClaim(t *testing.T) {
	claims := []string{
		"I'd like to work on this.",
		"Can I take this one?",
		"Could I pick this up?",
		"Please assign this to me",
		"/assign",
		"I'm working on it",
		"I prepared and pushed a focused fix on `someone:fix/completion-cleanup`",
		"PRs to this repo are limited to collaborators, so the fix is on a branch instead",
		"I could create a merge request with a fix and a reproduction test",
		"I’ll send a PR later today",
		"Here's a fix: https://github.com/someone/repo/commit/abc",
	}
	for _, body := range claims {
		if !IsClaim(body) {
			t.Errorf("IsClaim(%q) = false, want true", body)
		}
	}

	notClaims := []string{
		"Same here, this breaks our build.",
		"You are not on the latest version.",
		"Any update on this?",
		"> I'd like to work on this\n\nPlease do!",
		"It would be nice to make it tree-shakable instead",
		"This is a duplicate of #12",
	}
	for _, body := range notClaims {
		if IsClaim(body) {
			t.Errorf("IsClaim(%q) = true, want false", body)
		}
	}
}

func TestIsDecline(t *testing.T) {
	for _, body := range []string{"This is working as intended.", "Duplicate of #42", "We won't accept a PR for this", "wontfix"} {
		if !IsDecline(body) {
			t.Errorf("IsDecline(%q) = false, want true", body)
		}
	}
	for _, body := range []string{"Thanks, a PR is welcome!", "I can reproduce this."} {
		if IsDecline(body) {
			t.Errorf("IsDecline(%q) = true, want false", body)
		}
	}
}

func TestLabels(t *testing.T) {
	labels := []string{"bug", "good first issue", "help wanted", "needs repro", "status: blocked", "wontfix", "typescript"}
	if got, want := WelcomingLabels(labels), []string{"good first issue", "help wanted"}; !reflect.DeepEqual(got, want) {
		t.Errorf("WelcomingLabels = %v, want %v", got, want)
	}
	if got, want := BlockingLabels(labels), []string{"needs repro", "status: blocked", "wontfix"}; !reflect.DeepEqual(got, want) {
		t.Errorf("BlockingLabels = %v, want %v", got, want)
	}
}

func TestReadAIPolicy(t *testing.T) {
	cases := []struct {
		name  string
		guide string
		want  string
	}{
		{"no mention", "# Contributing\n\nRun the tests before you open a PR.", ""},
		{"restricted", "# Contributing\n\n## AI\n\nWe do not accept pull requests generated by AI tools.\nThey will be closed.", AIRestricted},
		{"disclose", "## AI-assisted contributions\n\nPR descriptions must be in your own words. Please disclose\nany use of LLMs.", AIDisclose},
		{"mentioned", "Our docs site uses an AI search widget.", AIMentioned},
		{"lowercase ai inside words is ignored", "Please maintain the existing style, as the maintainers said.", ""},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got := ReadAIPolicy(tc.guide)
			if got.Stance != tc.want {
				t.Errorf("stance = %q, want %q (excerpt %q)", got.Stance, tc.want, got.Excerpt)
			}
			if tc.want != "" && got.Excerpt == "" {
				t.Error("expected an excerpt")
			}
		})
	}
}

func TestMovedTo(t *testing.T) {
	readme := "🚨🚨🚨 `@date-fns/tz` has [moved to the date-fns monorepo](https://github.com/date-fns/date-fns/tree/main/pkgs/tz) 🚨🚨🚨\n\n# @date-fns/tz\n"
	target, notice := MovedTo(readme, "date-fns/tz")
	if target != "date-fns/date-fns" {
		t.Errorf("target = %q, want date-fns/date-fns", target)
	}
	if notice == "" {
		t.Error("expected the notice line")
	}

	if target, notice := MovedTo("# Project\n\nA fast library. See https://github.com/other/thing for docs.", "me/project"); target != "" || notice != "" {
		t.Errorf("unexpected move: %q %q", target, notice)
	}

	if target, _ := MovedTo("This project is no longer maintained.", "me/project"); target != "" {
		t.Errorf("target = %q, want empty for a notice with no new home", target)
	}
}

func TestKeywords(t *testing.T) {
	cases := []struct {
		title string
		want  []string
	}{
		{"tzOffset: wrong sign for offsets between -01:00 and 00:00", []string{"tzOffset", "offsets"}},
		{"`prefer-comparison-matcher`: fix turns a string comparison into `toBeLessThan`", []string{"prefer-comparison-matcher", "toBeLessThan", "comparison"}},
		{"res.send() with a non-Uint8Array typed array loses data", []string{"res.send", "non-Uint8Array"}},
	}
	for _, tc := range cases {
		if got := Keywords(tc.title); !reflect.DeepEqual(got[:min(len(got), len(tc.want))], tc.want) {
			t.Errorf("Keywords(%q) = %v, want prefix %v", tc.title, got, tc.want)
		}
	}
}

func TestSimilarity(t *testing.T) {
	issue := "tzOffset: wrong sign for offsets between -01:00 and 00:00"
	cases := []struct {
		title          string
		atLeast, below float64
	}{
		{"Fix tzOffset returning the wrong sign for sub-hour western offsets", 0.99, 1.01},
		{"fix(tz): correct tzOffset sign for negative offsets of less than an hour", 0.99, 1.01},
		{"fix(tz): support UTC offset format", 0.3, 0.4},
		{"", 0, 0.01},
	}
	for _, tc := range cases {
		if got := Similarity(issue, tc.title); got < tc.atLeast || got >= tc.below {
			t.Errorf("Similarity(%q) = %.2f, want [%.2f, %.2f)", tc.title, got, tc.atLeast, tc.below)
		}
	}
	if got := Similarity("", "anything"); got != 0 {
		t.Errorf("empty issue title = %.2f, want 0", got)
	}
}
